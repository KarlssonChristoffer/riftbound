"""Generate the arena's sound effects with the ElevenLabs sound-effects API (text -> sound).

Reads  assets/sfx/manifest.json   (the prompt list: id, prompt, dur, var, loop, infl, slice, gain)
Writes assets/sfx/<id>_<n>.mp3    (one file per variant; existing files are SKIPPED, so re-runs only fill gaps)
       assets/sfx/index.json      (what exists, for the browser loader: it can't list a directory over http)
       assets/sfx/.prompts.json   (the prompt each file was made from, to flag files whose prompt changed since)

The API key is read from the environment variable ELEVENLABS_API_KEY and never printed or written anywhere.
Python standard library only.

  python tools/sfx/gen_sfx.py --dry-run                 # what would be generated, how many seconds of audio
  python tools/sfx/gen_sfx.py --only "hit.*,brk.*"      # just some sounds (comma-separated globs)
  python tools/sfx/gen_sfx.py --max 5                   # at most 5 generations this run (try it out cheaply)
  python tools/sfx/gen_sfx.py --stale                   # regenerate files whose manifest prompt was edited
  python tools/sfx/gen_sfx.py --force --only explode    # regenerate (overwrites) explode_1..3
  python tools/sfx/gen_sfx.py --index                   # only rebuild index.json from the files on disk
"""
import argparse, fnmatch, json, os, re, sys, time, urllib.error, urllib.request
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SFX = ROOT / 'assets' / 'sfx'
MANIFEST, INDEX, PROMPTS = SFX / 'manifest.json', SFX / 'index.json', SFX / '.prompts.json'
API = 'https://api.elevenlabs.io/v1'
MODEL = 'eleven_text_to_sound_v2'
FORMAT = 'mp3_44100_128'
FILE_RE = re.compile(r'^(?P<id>.+)_(?P<n>\d+)\.mp3$')


def load_manifest():
    m = json.loads(MANIFEST.read_text(encoding='utf-8'))
    d, out = m.get('defaults', {}), []
    for s in m['sounds']:
        if 'id' not in s: continue   # {"group": ...} headings
        e = {**d, **s}
        if e.get('dur') is not None and not (.5 <= e['dur'] <= 30): sys.exit(f"{e['id']}: dur {e['dur']} outside 0.5-30 s")
        out.append(e)
    ids = [e['id'] for e in out]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup: sys.exit(f'duplicate ids in manifest: {sorted(dup)}')
    return out


def fname(sid, n): return f'{sid}_{n}.mp3'


def read_json(p, default):
    try: return json.loads(p.read_text(encoding='utf-8'))
    except (FileNotFoundError, json.JSONDecodeError): return default


def write_json(p, obj):
    tmp = p.with_suffix(p.suffix + '.tmp')
    tmp.write_text(json.dumps(obj, indent=1, ensure_ascii=False), encoding='utf-8'); tmp.replace(p)


def build_index(sounds):
    """index.json: {id: {files: [...], loop, slice, gain}} for every id with at least one file on disk."""
    have = {}
    for f in sorted(SFX.glob('*.mp3')):
        m = FILE_RE.match(f.name)
        if m: have.setdefault(m['id'], []).append((int(m['n']), f.name))
    idx = {}
    for e in sounds:
        files = [n for _, n in sorted(have.get(e['id'], []))]
        if files: idx[e['id']] = {'files': files, 'loop': bool(e.get('loop')), 'slice': bool(e.get('slice')), 'gain': e.get('gain', 0)}
    orphans = sorted(set(have) - {e['id'] for e in sounds})
    write_json(INDEX, {'_doc': 'generated by tools/sfx/gen_sfx.py from the files on disk; do not edit', 'sounds': idx})
    return idx, orphans


def api(key, path, body=None, timeout=120):
    req = urllib.request.Request(API + path, method='POST' if body is not None else 'GET',
                                 data=json.dumps(body).encode() if body is not None else None,
                                 headers={'xi-api-key': key, 'Content-Type': 'application/json', 'Accept': '*/*'})
    with urllib.request.urlopen(req, timeout=timeout) as r: return r.read()


def generate(key, e, n, out):
    body = {'text': e['prompt'], 'model_id': MODEL, 'prompt_influence': e.get('infl', .3)}
    if e.get('dur') is not None: body['duration_seconds'] = e['dur']
    if e.get('loop'): body['loop'] = True
    for attempt in range(6):
        try:
            data = api(key, f'/sound-generation?output_format={FORMAT}', body)
            if len(data) < 1000: raise RuntimeError(f'suspiciously small response ({len(data)} bytes)')
            tmp = out.with_suffix('.part'); tmp.write_bytes(data); tmp.replace(out)
            return len(data)
        except urllib.error.HTTPError as err:
            msg = err.read().decode('utf-8', 'replace')[:400]
            if err.code in (429, 500, 502, 503, 504) and attempt < 5:
                wait = 2 ** (attempt + 1); print(f'  {out.name}: HTTP {err.code}, retrying in {wait}s'); time.sleep(wait); continue
            raise RuntimeError(f'HTTP {err.code}: {msg}') from None
        except (urllib.error.URLError, TimeoutError) as err:
            if attempt < 5: time.sleep(2 ** (attempt + 1)); continue
            raise RuntimeError(f'network: {err}') from None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--only', help='comma-separated id globs, e.g. "step.*,explode"')
    ap.add_argument('--dry-run', action='store_true', help='list what would be generated, call nothing')
    ap.add_argument('--force', action='store_true', help='regenerate even if the file exists (use with --only)')
    ap.add_argument('--stale', action='store_true', help='regenerate files whose prompt changed in the manifest')
    ap.add_argument('--max', type=int, default=0, help='stop after this many generations (0 = no limit)')
    ap.add_argument('--variants', type=int, default=0, help='override the variant count of every selected sound')
    ap.add_argument('--jobs', type=int, default=2, help='parallel requests (your plan limits concurrency)')
    ap.add_argument('--index', action='store_true', help='only rebuild index.json from the files on disk')
    a = ap.parse_args()

    SFX.mkdir(parents=True, exist_ok=True)
    sounds = load_manifest()
    if a.index:
        idx, orphans = build_index(sounds)
        print(f'index.json: {len(idx)} sounds, {sum(len(v["files"]) for v in idx.values())} files'
              + (f'; files with no manifest entry: {orphans}' if orphans else '')); return

    globs = [g.strip() for g in a.only.split(',')] if a.only else ['*']
    sel = [e for e in sounds if any(fnmatch.fnmatchcase(e['id'], g) for g in globs)]
    if not sel: sys.exit(f'no manifest ids match {globs}')
    prompts = read_json(PROMPTS, {})

    jobs = []   # (entry, n, path, reason)
    for e in sel:
        for n in range(1, (a.variants or e.get('var', 1)) + 1):
            p = SFX / fname(e['id'], n)
            stale = p.exists() and prompts.get(p.name) not in (None, e['prompt'])
            if not p.exists(): jobs.append((e, n, p, 'new'))
            elif a.force: jobs.append((e, n, p, 'force'))
            elif a.stale and stale: jobs.append((e, n, p, 'stale'))
    if a.max: jobs = jobs[:a.max]

    stale_all = sorted({FILE_RE.match(f)['id'] for f, pr in prompts.items() if FILE_RE.match(f) and (SFX / f).exists()
                        and any(e['id'] == FILE_RE.match(f)['id'] and e['prompt'] != pr for e in sounds)})
    secs = sum(e.get('dur') or 5 for e, *_ in jobs)
    print(f'{len(sel)} sounds selected, {len(jobs)} files to generate, ~{secs:.0f} s of audio'
          + (' (dur null counted as 5 s)' if any(e.get('dur') is None for e, *_ in jobs) else ''))
    if stale_all and not a.stale: print(f'prompt changed since generation (run --stale to redo): {stale_all}')
    if a.dry_run:
        for e, n, p, why in jobs: print(f'  {why:5}  {p.name:28} {e.get("dur") or "auto":>5}s{"  loop" if e.get("loop") else ""}{"  slice" if e.get("slice") else ""}')
        return
    if not jobs:
        idx, _ = build_index(sounds); print(f'nothing to do; index.json lists {len(idx)} sounds'); return

    key = os.environ.get('ELEVENLABS_API_KEY', '').strip()
    if not key: sys.exit('Set the ELEVENLABS_API_KEY environment variable first (the key is read from there only).')
    try:
        sub = json.loads(api(key, '/user/subscription', timeout=20))
        used, lim = sub.get('character_count'), sub.get('character_limit')
        if used is not None and lim: print(f'credits: {used:,} of {lim:,} used this period ({sub.get("tier", "?")} tier)')
    except Exception as err:   # informative only; the key may not have the user_read permission
        print(f'(could not read the subscription: {str(err)[:80]})')

    ok = fail = 0; t0 = time.time()
    with ThreadPoolExecutor(max_workers=max(1, a.jobs)) as pool:
        futs = {pool.submit(generate, key, e, n, p): (e, n, p) for e, n, p, _ in jobs}
        for f in as_completed(futs):
            e, n, p = futs[f]
            try:
                size = f.result(); ok += 1; prompts[p.name] = e['prompt']; write_json(PROMPTS, prompts)
                print(f'  ok   {p.name:28} {size / 1024:6.0f} KB   [{ok + fail}/{len(jobs)}]')
            except Exception as err:
                fail += 1; print(f'  FAIL {p.name:28} {err}')
                if 'HTTP 401' in str(err) or 'quota' in str(err).lower():
                    print('  stopping: authentication / quota problem'); pool.shutdown(cancel_futures=True); break
    idx, orphans = build_index(sounds)
    print(f'done in {time.time() - t0:.0f}s: {ok} ok, {fail} failed. index.json lists {len(idx)} sounds.'
          + (f' Files with no manifest entry: {orphans}' if orphans else ''))
    if fail: sys.exit(1)


if __name__ == '__main__':
    main()
